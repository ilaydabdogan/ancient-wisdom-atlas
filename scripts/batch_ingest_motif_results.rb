#!/usr/bin/env ruby
# frozen_string_literal: true

require_relative "batch_common"

options = {
  output_dir: nil,
  force: false
}

OptionParser.new do |parser|
  parser.banner = "usage: ruby scripts/batch_ingest_motif_results.rb --run-id RUN_ID [options]"
  parser.on("--run-id RUN_ID", "Batch run id") { |value| options[:run_id] = value }
  parser.on("--output-dir PATH", "Draft extraction output dir") { |value| options[:output_dir] = value }
  parser.on("--force", "Replace changed draft extraction files") { options[:force] = true }
end.parse!

AtlasBatch.die("--run-id is required", 64) unless options[:run_id]

REQUIRED_TOP_LEVEL = %w[
  record_id source_text_path passage_locator canonical_text literal_observations
  figures roles symbols scenes candidate_motifs comparison_claims evidence confidence
  reviewer_status extracted_by extracted_at notes
].freeze

ARRAY_FIELDS = %w[
  literal_observations figures roles symbols scenes candidate_motifs comparison_claims evidence
].freeze

def load_request_index(manifest)
  path = AtlasBatch.project_path(manifest.dig("artifacts", "requests_index_path").to_s)
  AtlasBatch.die("requests index not found; run scripts/batch_prepare_motif_requests.rb first", 66) unless File.file?(path)

  [path, AtlasBatch.load_yaml(path)]
end

def response_text(body)
  return body["output_text"] if body["output_text"].is_a?(String)

  Array(body["output"]).each do |output_item|
    Array(output_item["content"]).each do |content|
      return content["text"] if content["text"].is_a?(String)
      return content["content"] if content["content"].is_a?(String)
    end
  end

  choice = body.dig("choices", 0, "message", "content")
  return choice if choice.is_a?(String)

  nil
end

def parse_json_text(text)
  cleaned = text.to_s.strip
  cleaned = cleaned.sub(/\A```(?:json)?\s*/i, "").sub(/\s*```\z/, "")
  JSON.parse(cleaned)
rescue JSON::ParserError
  if (match = cleaned.match(/\{.*\}/m))
    JSON.parse(match[0])
  else
    raise
  end
end

def validate_record(record)
  errors = []
  REQUIRED_TOP_LEVEL.each do |key|
    errors << "missing #{key}" unless record.key?(key)
  end
  ARRAY_FIELDS.each do |key|
    errors << "#{key} must be an array" unless record[key].is_a?(Array)
  end
  errors << "passage_locator must be an object" unless record["passage_locator"].is_a?(Hash)
  errors << "confidence must be an object" unless record["confidence"].is_a?(Hash)
  errors << "reviewer_status must be an object" unless record["reviewer_status"].is_a?(Hash)
  errors
end

def normalize_record(record, request_map, manifest, model)
  locator = request_map.fetch("locator")
  existing_locator = record["passage_locator"].is_a?(Hash) ? record["passage_locator"] : {}
  source_path = request_map.fetch("source_text_path")

  record["record_id"] = request_map.fetch("record_id")
  record["source_text_path"] = source_path
  record["passage_locator"] = {
    "label" => locator.fetch("label"),
    "start" => locator.fetch("start_line").to_s,
    "end" => locator.fetch("end_line").to_s,
    "translation" => existing_locator["translation"].to_s,
    "notes" => "Generated from OpenAI Batch run #{manifest.fetch("run_id")}; human review required."
  }
  record["canonical_text"] ||= {
    "quote" => "",
    "summary" => "",
    "language" => "",
    "quote_policy" => "summarized"
  }
  record["canonical_text"]["quote"] ||= ""
  record["canonical_text"]["summary"] ||= ""
  record["canonical_text"]["language"] ||= ""
  record["canonical_text"]["quote_policy"] ||= "summarized"

  ARRAY_FIELDS.each do |key|
    record[key] = [] unless record[key].is_a?(Array)
  end

  Array(record["evidence"]).each do |evidence|
    next unless evidence.is_a?(Hash)

    evidence["source_text_path"] = source_path if evidence["source_text_path"].to_s.strip.empty?
  end

  record["confidence"] ||= {}
  record["confidence"]["extraction"] ||= "uncertain"
  record["confidence"]["motif_candidates"] ||= "uncertain"
  record["confidence"]["comparison_claims"] ||= "uncertain"
  record["confidence"]["notes"] ||= "Generated by batch pipeline; verify before treating as reviewed corpus data."
  record["reviewer_status"] = {
    "status" => "needs_review",
    "reviewer" => "",
    "reviewed_at" => "",
    "notes" => "Machine-generated draft from OpenAI Batch; not human-reviewed."
  }
  record["extracted_by"] = "openai_batch:#{model}"
  record["extracted_at"] = Date.today.iso8601
  record["notes"] = [
    record["notes"].to_s.strip,
    "batch_run_id=#{manifest.fetch("run_id")}",
    "custom_id=#{request_map.fetch("custom_id")}",
    "passage_sha256=#{request_map.fetch("passage_sha256")}"
  ].reject(&:empty?).join("\n")
  record
end

def output_path_for(record, request_map, run_id, output_dir)
  source_slug = AtlasBatch.safe_filename(File.basename(request_map.fetch("source_text_path"), ".md"))
  filename = "#{AtlasBatch.safe_filename(record.fetch("record_id"))}.yml"
  File.join(output_dir, source_slug, filename)
end

run_id = options.fetch(:run_id)
manifest = AtlasBatch.load_manifest(run_id)
_index_path, request_index = load_request_index(manifest)
request_map_path = AtlasBatch.project_path(manifest.dig("artifacts", "request_map_path").to_s)
AtlasBatch.die("request map not found: #{AtlasBatch.relative_path(request_map_path)}", 66) unless File.file?(request_map_path)

request_map = AtlasBatch.read_jsonl(request_map_path).to_h { |record| [record.fetch("custom_id"), record] }
model = request_index["model"] || manifest.dig("config", "motif_request_generation", "model") || "unknown"
output_dir = AtlasBatch.project_path(options[:output_dir] || File.join("extractions", "generated", "openai-batch", run_id))
ingest_index_path = File.join(AtlasBatch.batch_dir(run_id), "ingested-results.jsonl")
ingest_records = File.file?(ingest_index_path) ? AtlasBatch.read_jsonl(ingest_index_path) : []

ingested = 0
skipped = 0
failed = 0

request_index.fetch("shards", []).each do |shard|
  output_path = shard["output_path"]
  next if output_path.to_s.empty?

  AtlasBatch.read_jsonl(AtlasBatch.project_path(output_path)).each do |line|
    custom_id = line["custom_id"]
    mapping = request_map[custom_id]
    unless mapping
      failed += 1
      ingest_records = AtlasBatch.append_unique(
        ingest_records,
        { "custom_id" => custom_id, "status" => "failed", "error" => "custom_id missing from request map" },
        "custom_id"
      )
      next
    end

    if line["error"]
      failed += 1
      ingest_records = AtlasBatch.append_unique(
        ingest_records,
        { "custom_id" => custom_id, "status" => "failed", "error" => line["error"], "updated_at" => AtlasBatch.utc_now },
        "custom_id"
      )
      next
    end

    response = line["response"] || {}
    if response["status_code"] && response["status_code"].to_i != 200
      failed += 1
      ingest_records = AtlasBatch.append_unique(
        ingest_records,
        { "custom_id" => custom_id, "status" => "failed", "error" => response, "updated_at" => AtlasBatch.utc_now },
        "custom_id"
      )
      next
    end

    body = response["body"] || {}
    if body["status"] == "incomplete" || body["incomplete_details"]
      failed += 1
      ingest_records = AtlasBatch.append_unique(
        ingest_records,
        {
          "custom_id" => custom_id,
          "status" => "failed",
          "error" => {
            "type" => "incomplete_response",
            "response_status" => body["status"],
            "incomplete_details" => body["incomplete_details"],
            "max_output_tokens" => body["max_output_tokens"],
            "model" => body["model"]
          },
          "updated_at" => AtlasBatch.utc_now
        },
        "custom_id"
      )
      next
    end

    begin
      text = response_text(body)
      raise "empty response text" if text.to_s.strip.empty?
      parsed = parse_json_text(text)
      normalized = normalize_record(parsed, mapping, manifest, model)
      validation_errors = validate_record(normalized)
      raise validation_errors.join("; ") if validation_errors.any?

      draft_path = output_path_for(normalized, mapping, run_id, output_dir)
      yaml = "#{YAML.dump(normalized)}\n"
      result = AtlasBatch.write_if_changed(draft_path, yaml, force: options[:force])
      status = result == :unchanged ? "unchanged" : "ingested"
      ingested += 1 unless result == :unchanged
      skipped += 1 if result == :unchanged
      ingest_records = AtlasBatch.append_unique(
        ingest_records,
        {
          "custom_id" => custom_id,
          "status" => "ingested",
          "record_id" => normalized.fetch("record_id"),
          "output_path" => AtlasBatch.relative_path(draft_path),
          "record_sha256" => AtlasBatch.sha256_text(yaml),
          "updated_at" => AtlasBatch.utc_now
        },
        "custom_id"
      )
      puts "#{status} #{custom_id} -> #{AtlasBatch.relative_path(draft_path)}"
    rescue StandardError => e
      failed += 1
      ingest_records = AtlasBatch.append_unique(
        ingest_records,
        { "custom_id" => custom_id, "status" => "failed", "error" => e.message, "updated_at" => AtlasBatch.utc_now },
        "custom_id"
      )
      warn "failed #{custom_id}: #{e.message}"
    end
  end
end

AtlasBatch.write_jsonl(ingest_index_path, ingest_records, force: true)

manifest["status"] = "results_ingested" if failed.zero? && (ingested.positive? || skipped.positive?)
manifest["artifacts"]["ingested_results_path"] = AtlasBatch.relative_path(ingest_index_path)
manifest["artifacts"]["generated_extractions_dir"] = AtlasBatch.relative_path(output_dir)
manifest["counts"] ||= {}
manifest["counts"]["ingested_records"] = ingest_records.count { |record| record["status"] == "ingested" }
manifest["counts"]["failed_ingestions"] = ingest_records.count { |record| record["status"] == "failed" }
manifest["state"]["last_ingest_at"] = AtlasBatch.utc_now
AtlasBatch.save_manifest(manifest)

puts "ingested #{ingested}, unchanged #{skipped}, failed #{failed}"
exit 1 if failed.positive?
